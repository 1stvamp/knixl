    #[test]
    fn flake_lock_problems_compare_each_top_level_input() {
        let expected = std::collections::BTreeMap::from([
            ("nixpkgs".to_string(), "aaa".to_string()),
            ("disko".to_string(), "bbb".to_string()),
        ]);
        // `nixpkgs_2` mirrors how nix names a node when a transitive input shares the name.
        let lock = r#"{
          "nodes": {
            "disko": { "locked": { "rev": "bbb" } },
            "nixpkgs_2": { "locked": { "rev": "aaa" } },
            "root": { "inputs": { "disko": "disko", "nixpkgs": "nixpkgs_2" } }
          },
          "root": "root",
          "version": 7
        }"#;
        assert!(flake_lock_problems(Some(lock), &expected).is_empty());

        let stale = lock.replace("\"rev\": \"aaa\"", "\"rev\": \"zzz\"");
        let problems = flake_lock_problems(Some(&stale), &expected);
        assert_eq!(problems.len(), 1, "{problems:?}");
        assert!(problems[0].contains("pins `nixpkgs` at zzz, knixl.lock.kdl at aaa"));

        let missing = flake_lock_problems(None, &expected);
        assert!(missing[0].contains("is missing"), "{missing:?}");

        let no_disko = lock.replace("\"disko\": \"disko\", ", "");
        assert!(
            flake_lock_problems(Some(&no_disko), &expected)[0].contains("no locked input `disko`")
        );
    }
