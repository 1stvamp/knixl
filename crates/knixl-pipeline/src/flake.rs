    #[test]
    fn pinned_url_writes_the_rev_into_the_ref() {
        assert_eq!(pinned_url("github:o/r", "abc"), "github:o/r/abc");
        assert_eq!(
            pinned_url("github:o/r?dir=x", "abc"),
            "github:o/r/abc?dir=x"
        );
        assert_eq!(
            pinned_url("git+https://example.com/r", "abc"),
            "git+https://example.com/r?rev=abc"
        );
        assert_eq!(
            pinned_url("git+https://example.com/r?ref=main", "abc"),
            "git+https://example.com/r?ref=main&rev=abc"
        );
    }

    #[test]
    fn input_flake_pins_inputs_and_builds_with_nixos_system() {
        let out = render_input_flake(&inputs(), &hosts(), &[], "25.11", None);
        assert!(out.contains("\"nixpkgs\" = {\n      url = \"github:NixOS/nixpkgs/rev-np\";"));
        assert!(out.contains("url = \"github:nix-community/disko/rev-disko\";"));
        assert!(out.contains("inputs.\"nixpkgs\".follows = \"nixpkgs\";"));
        assert!(out.contains("outputs = { nixpkgs, ... }@inputs:"));
        assert!(out
            .contains("\"web\" = nixpkgs.lib.nixosSystem {\n          system = \"x86_64-linux\";"));
        assert!(out
            .contains("\"db\" = nixpkgs.lib.nixosSystem {\n          system = \"aarch64-linux\";"));
        assert!(!out.contains("fetchGit"), "{out}");
        assert!(!out.contains("formatter"), "{out}");
        assert!(
            out.find("\"disko\" = {").unwrap() < out.find("\"nixpkgs\" = {").unwrap(),
            "inputs in name order: {out}"
        );
        let mut reversed = inputs();
        reversed.reverse();
        assert_eq!(
            render_input_flake(&reversed, &hosts(), &[], "25.11", None),
            out
        );
    }

