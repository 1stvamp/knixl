//! Emit the opt-in system-assembly flake (ADR 0009): nixosConfigurations.<host>, each host
//! built against its own baseline nixpkgs rev, pinned by fetchGit (a full rev is a pure pin).

#[derive(Clone, PartialEq, Eq, Debug)]
pub struct FlakeHost {
    pub name: String,
    pub baseline_rev: String,
    pub module_path: String,
    /// The host's declared `system` double, passed to `nixosSystem` in input mode.
    pub system: Option<String>,
    /// Input-mode module expressions listed ahead of the host module, e.g.
    /// `inputs."disko".nixosModules."disko"` (ADR 0014).
    pub input_modules: Vec<String>,
    /// Input-mode inline module expressions listed after the host module (the sops wiring).
    pub inline_modules: Vec<String>,
}

/// An image target (ADR 0012, 0013): an installer ISO or an lxc image. `system` is the platform
/// double keying its `packages.<system>` output; `baseline_rev` pins nixpkgs like a host; `kind`
/// selects the flake output shape.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct FlakeImage {
    pub name: String,
    pub baseline_rev: String,
    pub module_path: String,
    pub system: String,
    pub kind: crate::project::ImageKind,
}

impl FlakeImage {
    /// The `packages.<system>` outputs this image contributes, as `(output-name, expression)`
    /// where the expression reads a build product off the image's evaluated config (`binding`).
    fn outputs(&self, binding: &str) -> Vec<(String, String)> {
        match self.kind {
            crate::project::ImageKind::Installer => vec![(
                format!("{}-iso", self.name),
                format!("{binding}.config.system.build.isoImage"),
            )],
            // incus image import takes both a rootfs and a metadata tarball, so both are exposed.
            crate::project::ImageKind::GuestLxc => vec![
                (
                    format!("{}-lxc", self.name),
                    format!("{binding}.config.system.build.tarball"),
                ),
                (
                    format!("{}-lxc-metadata", self.name),
                    format!("{binding}.config.system.build.metadata"),
                ),
            ],
        }
    }
}

/// A Nix identifier derived from an image name for a `let` binding (names are simple in practice,
/// but hyphens and other non-ident chars are mapped to `_` defensively).
fn let_ident(name: &str) -> String {
    let mut out = String::from("image_");
    for c in name.chars() {
        out.push(if c.is_ascii_alphanumeric() { c } else { '_' });
    }
    out
}

/// Escape a value spliced into a Nix double-quoted string literal: backslash, double-quote,
/// and the antiquotation opener `${`.
fn esc(v: &str) -> String {
    v.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace("${", "\\${")
}

/// Render the system flake. Hosts are emitted in `name` order so the output is a pure function
/// of the input set (sorted here defensively, independent of caller order). The text is
/// unformatted Nix; the caller runs it through the pinned formatter before hashing.
///
/// Each host is built with `nixos/lib/eval-config.nix` from its baseline nixpkgs: that is the
/// self-contained system constructor. `lib.nixosSystem` is a flake-only lib extension and is
/// NOT present on a plain `import <nixpkgs> {}` set, so it cannot be used here. `fetchGit` with
/// a full rev is a pure pin; `shallow = true` matches the package-pin emit idiom.
pub fn render_system_flake(
    hosts: &[FlakeHost],
    images: &[FlakeImage],
    state_version: &str,
    nixpkgs_url: &str,
) -> String {
    let mut sorted: Vec<&FlakeHost> = hosts.iter().collect();
    sorted.sort_by(|a, b| a.name.cmp(&b.name));
    let mut inst: Vec<&FlakeImage> = images.iter().collect();
    inst.sort_by(|a, b| a.name.cmp(&b.name));

    let mut s = String::new();
    s.push_str("# Generated by knixl. Do NOT edit; regenerate with `knixl generate`.\n");
    s.push_str("{\n");
    s.push_str("  description = \"knixl-generated system\";\n");
    s.push_str("  outputs = { ... }:\n");
    s.push_str("    let\n");
    s.push_str(&format!(
        "      evalAt = rev: import \"${{builtins.fetchGit {{ url = \"{}\"; rev = rev; shallow = true; }}}}/nixos/lib/eval-config.nix\";\n",
        esc(nixpkgs_url)
    ));
    // One `let` binding per image target, so both nixosConfigurations and packages can name the
    // same evaluated configuration (ADR 0012, 0013).
    for i in &inst {
        s.push_str(&format!(
            "      {} = evalAt \"{}\" {{\n",
            let_ident(&i.name),
            esc(&i.baseline_rev)
        ));
        s.push_str("        modules = [\n");
        s.push_str(&format!("          {}\n", i.module_path));
        s.push_str(&format!(
            "          {{ system.stateVersion = \"{}\"; }}\n",
            esc(state_version)
        ));
        s.push_str("        ];\n");
        s.push_str("      };\n");
    }
    s.push_str("    in\n");
    s.push_str("    {\n");
    s.push_str("      nixosConfigurations = {\n");
    for h in sorted {
        s.push_str(&format!(
            "        \"{}\" = evalAt \"{}\" {{\n",
            esc(&h.name),
            esc(&h.baseline_rev)
        ));
        s.push_str("          modules = [\n");
        s.push_str(&format!("            {}\n", h.module_path));
        s.push_str(&format!(
            "            {{ system.stateVersion = \"{}\"; }}\n",
            esc(state_version)
        ));
        s.push_str("          ];\n");
        s.push_str("        };\n");
    }
    for i in &inst {
        s.push_str(&format!(
            "        \"{}\" = {};\n",
            esc(&i.name),
            let_ident(&i.name)
        ));
    }
    s.push_str("      };\n");
    push_packages(&mut s, &inst);
    s.push_str("    };\n");
    s.push_str("}\n");
    s
}

/// Image build outputs, grouped by target system (so two images on the same system share one
/// `packages.<system>` set rather than emitting a duplicate key).
fn push_packages(s: &mut String, inst: &[&FlakeImage]) {
    if inst.is_empty() {
        return;
    }
    let mut by_system: std::collections::BTreeMap<&str, Vec<(String, String)>> =
        std::collections::BTreeMap::new();
    for i in inst {
        by_system
            .entry(i.system.as_str())
            .or_default()
            .extend(i.outputs(&let_ident(&i.name)));
    }
    s.push_str("      packages = {\n");
    for (system, mut outs) in by_system {
        outs.sort_by(|a, b| a.0.cmp(&b.0));
        s.push_str(&format!("        \"{}\" = {{\n", esc(system)));
        for (name, expr) in outs {
            s.push_str(&format!("          \"{}\" = {};\n", esc(&name), expr));
        }
        s.push_str("        };\n");
    }
    s.push_str("      };\n");
}

/// A flake input as the generated flake declares it (ADR 0014): `url` already carries the
/// pinned rev, `follows` is sorted by key.
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct FlakeInputSpec {
    pub name: String,
    pub url: String,
    pub flake: bool,
    pub follows: Vec<(String, String)>,
}

/// Write `rev` into a flake ref so it locks to exactly that commit: the path form for
/// `github:` refs (`github:owner/repo/<rev>`), a `rev` query parameter otherwise.
pub fn pinned_url(url: &str, rev: &str) -> String {
    if url.starts_with("github:") {
        return match url.split_once('?') {
            Some((path, query)) => format!("{path}/{rev}?{query}"),
            None => format!("{url}/{rev}"),
        };
    }
    let sep = if url.contains('?') { '&' } else { '?' };
    format!("{url}{sep}rev={rev}")
}

/// Render the input-mode system flake (ADR 0014): declared inputs pinned by rev, every host
/// and image built with `nixpkgs.lib.nixosSystem` from the `nixpkgs` input. Hosts pass their
/// `system` when known, and installers pass theirs; guest images don't, since the lxc base
/// module sets the platform. Inputs, hosts and images are emitted in name order.
pub fn render_input_flake(
    inputs: &[FlakeInputSpec],
    hosts: &[FlakeHost],
    images: &[FlakeImage],
    state_version: &str,
    formatter: Option<&str>,
) -> String {
    let mut ins: Vec<&FlakeInputSpec> = inputs.iter().collect();
    ins.sort_by(|a, b| a.name.cmp(&b.name));
    let mut sorted: Vec<&FlakeHost> = hosts.iter().collect();
    sorted.sort_by(|a, b| a.name.cmp(&b.name));
    let mut inst: Vec<&FlakeImage> = images.iter().collect();
    inst.sort_by(|a, b| a.name.cmp(&b.name));

    let modules =
        |s: &mut String, indent: &str, before: &[String], path: &str, after: &[String]| {
            s.push_str(&format!("{indent}modules = [\n"));
            for m in before {
                s.push_str(&format!("{indent}  {m}\n"));
            }
            s.push_str(&format!("{indent}  {path}\n"));
            for m in after {
                s.push_str(&format!("{indent}  {m}\n"));
            }
            s.push_str(&format!(
                "{indent}  {{ system.stateVersion = \"{}\"; }}\n",
                esc(state_version)
            ));
            s.push_str(&format!("{indent}];\n"));
        };

    let mut s = String::new();
    s.push_str("# Generated by knixl. Do NOT edit; regenerate with `knixl generate`.\n");
    s.push_str("{\n");
    s.push_str("  description = \"knixl-generated system\";\n");
    s.push_str("  inputs = {\n");
    for i in &ins {
        s.push_str(&format!("    \"{}\" = {{\n", esc(&i.name)));
        s.push_str(&format!("      url = \"{}\";\n", esc(&i.url)));
        if !i.flake {
            s.push_str("      flake = false;\n");
        }
        for (key, target) in &i.follows {
            s.push_str(&format!(
                "      inputs.\"{}\".follows = \"{}\";\n",
                esc(key),
                esc(target)
            ));
        }
        s.push_str("    };\n");
    }
    s.push_str("  };\n");
    s.push_str("  outputs = { nixpkgs, ... }@inputs:\n");
    s.push_str("    let\n");
    for i in &inst {
        s.push_str(&format!(
            "      {} = nixpkgs.lib.nixosSystem {{\n",
            let_ident(&i.name)
        ));
        if i.kind == crate::project::ImageKind::Installer {
            s.push_str(&format!("        system = \"{}\";\n", esc(&i.system)));
        }
        modules(&mut s, "        ", &[], &i.module_path, &[]);
        s.push_str("      };\n");
    }
    s.push_str("    in\n");
    s.push_str("    {\n");
    s.push_str("      nixosConfigurations = {\n");
    for h in &sorted {
        s.push_str(&format!(
            "        \"{}\" = nixpkgs.lib.nixosSystem {{\n",
            esc(&h.name)
        ));
        if let Some(system) = &h.system {
            s.push_str(&format!("          system = \"{}\";\n", esc(system)));
        }
        modules(
            &mut s,
            "          ",
            &h.input_modules,
            &h.module_path,
            &h.inline_modules,
        );
        s.push_str("        };\n");
    }
    for i in &inst {
        s.push_str(&format!(
            "        \"{}\" = {};\n",
            esc(&i.name),
            let_ident(&i.name)
        ));
    }
    s.push_str("      };\n");
    push_packages(&mut s, &inst);
    if let Some(attr) = formatter {
        let systems: std::collections::BTreeSet<&str> =
            sorted.iter().filter_map(|h| h.system.as_deref()).collect();
        if !systems.is_empty() {
            s.push_str("      formatter = {\n");
            for system in systems {
                s.push_str(&format!(
                    "        \"{0}\" = nixpkgs.legacyPackages.\"{0}\".\"{1}\";\n",
                    esc(system),
                    esc(attr)
                ));
            }
            s.push_str("      };\n");
        }
    }
    s.push_str("    };\n");
    s.push_str("}\n");
    s
}

/// Compare a nix-written `generated/flake.lock` against the revs `knixl.lock.kdl` pins for each
/// top-level input (ADR 0014). `None` means the file is missing, which is itself a problem: the
/// generated flake only reproduces with its lock committed beside it.
pub fn flake_lock_problems(
    lock_text: Option<&str>,
    expected: &std::collections::BTreeMap<String, String>,
) -> Vec<String> {
    const RELOCK: &str = "re-lock with `nix flake lock` in generated/, or run `knixl upgrade` \
                          if knixl.lock.kdl is the side that is behind";
    let Some(text) = lock_text else {
        return vec![
            "generated/flake.lock is missing: run `nix flake lock` in generated/ and commit it"
                .into(),
        ];
    };
    let json: serde_json::Value = match serde_json::from_str(text) {
        Ok(v) => v,
        Err(e) => return vec![format!("generated/flake.lock does not parse: {e}")],
    };
    let nodes = &json["nodes"];
    let root = &nodes[json["root"].as_str().unwrap_or("root")];
    let mut problems = Vec::new();
    for (name, want) in expected {
        let locked = root["inputs"][name]
            .as_str()
            .and_then(|key| nodes[key]["locked"]["rev"].as_str());
        match locked {
            None => problems.push(format!(
                "generated/flake.lock has no locked input `{name}`: {RELOCK}"
            )),
            Some(got) if got != want => problems.push(format!(
                "generated/flake.lock pins `{name}` at {got}, knixl.lock.kdl at {want}: {RELOCK}"
            )),
            Some(_) => {}
        }
    }
    problems
}

