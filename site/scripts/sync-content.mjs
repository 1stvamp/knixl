// Generate the site's docs, examples and changelog pages from their sources on main, so the
// site cannot drift from the repo. Everything written here is gitignored.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, posix, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = resolve(SITE, '..');
const CONTENT = join(SITE, 'src/content/docs');
const GITHUB = 'https://github.com/1stvamp/knixl';

const read = (p) => readFileSync(join(REPO, p), 'utf8');

const VERSION = read('Cargo.toml').match(/^version = "([^"]+)"/m)?.[1];
if (!VERSION) throw new Error('no workspace version in Cargo.toml');

/**
 * A golden output as the current release writes it. The goldens are generated with a fixed test
 * tool version, and the header line naming it is the only part that differs from a real run.
 */
const golden = (p) => read(p).replace(/^# Generated by knixl \S+ /m, `# Generated by knixl ${VERSION} `);

/** Pages generated from a repo file: repo path -> site route. Filled before any link rewrite. */
const routes = new Map();

function docPages() {
	const pages = [];
	for (const name of readdirSync(join(REPO, 'docs')).sort()) {
		const m = name.match(/^(\d\d)-(.+)\.md$/);
		if (m) pages.push({ src: `docs/${name}`, out: `docs/${m[2]}.md`, route: `/docs/${m[2]}/`, order: Number(m[1]) });
	}
	for (const name of readdirSync(join(REPO, 'docs/adr')).sort()) {
		const m = name.match(/^(\d{4})-(.+)\.md$/);
		if (m) pages.push({ src: `docs/adr/${name}`, out: `adr/${m[1]}-${m[2]}.md`, route: `/adr/${m[1]}-${m[2]}/`, order: Number(m[1]) });
	}
	return pages;
}

/** Split a document into its first `# ` heading and the rest. */
function splitTitle(text, fallback) {
	const lines = text.split('\n');
	const i = lines.findIndex((l) => l.startsWith('# '));
	if (i === -1) return { title: fallback, body: text };
	return { title: lines[i].slice(2).trim(), body: [...lines.slice(0, i), ...lines.slice(i + 1)].join('\n').trimStart() };
}

/**
 * Point a markdown link written relative to `from` (a repo path) at the site page for that file,
 * or at the file on GitHub when the site has no page for it. External and in-page links are
 * left alone.
 */
function rewriteTarget(target, from) {
	if (/^([a-z][a-z0-9+.-]*:|#|\/)/i.test(target)) return target;
	const [path, anchor] = target.split('#');
	if (!path) return target;
	const repoPath = posix.normalize(posix.join(posix.dirname(from), path));
	if (repoPath.startsWith('..')) return target;
	const hash = anchor ? `#${anchor}` : '';
	const route = routes.get(repoPath);
	if (route) return route + hash;
	return `${GITHUB}/blob/main/${repoPath}${hash}`;
}

function rewriteLinks(text, from) {
	// Only rewrite outside fenced code blocks, where `](...)` can be literal source.
	return text
		.split(/(^```[\s\S]*?^```)/m)
		.map((chunk, i) =>
			i % 2 === 1
				? chunk
				: chunk.replace(/(!?\[[^\]]*\]\()([^)\s]+)(\))/g, (_, a, t, b) => a + rewriteTarget(t, from) + b),
		)
		.join('');
}

const yaml = (s) => JSON.stringify(s);

function frontmatter(fields) {
	const lines = ['---'];
	for (const [k, v] of Object.entries(fields)) {
		if (v === undefined) continue;
		if (typeof v === 'object') {
			lines.push(`${k}:`);
			for (const [k2, v2] of Object.entries(v)) lines.push(`  ${k2}: ${typeof v2 === 'string' ? yaml(v2) : v2}`);
		} else lines.push(`${k}: ${typeof v === 'string' ? yaml(v) : v}`);
	}
	lines.push('---', '');
	return lines.join('\n');
}

function write(out, text) {
	const path = join(CONTENT, out);
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, text);
}

/** The `./x.nix` side-files a generated host module imports (knixl names them after the host). */
function sideFiles(nix) {
	return [...nix.matchAll(/^\s+\.\/([\w.-]+)\.nix$/gm)].map((m) => m[1]);
}

/** The module nodes a host block uses: its direct children, minus host metadata. */
function hostModules(kdl) {
	const meta = new Set(['system', 'hostname', 'nixpkgs', 'oracle-modules']);
	const names = [...kdl.matchAll(/^ {4}([a-z][\w-]*)/gm)].map((m) => m[1]).filter((n) => !meta.has(n));
	return [...new Set(names)];
}

function examplePages() {
	return readdirSync(join(REPO, 'examples/hosts'))
		.filter((n) => n.endsWith('.kdl'))
		.sort()
		.map((n) => n.slice(0, -4));
}

function exampleFiles(host) {
	const main = golden(`examples/expected/${host}.nix`);
	return [
		{ name: `generated/hosts/${host}.nix`, text: main },
		...sideFiles(main)
			.filter((s) => existsSync(join(REPO, `examples/expected/${s}.nix`)))
			.map((s) => ({ name: `generated/hosts/${s}.nix`, text: golden(`examples/expected/${s}.nix`) })),
	];
}

const list = (xs) => (xs.length < 2 ? xs.join('') : `${xs.slice(0, -1).join(', ')} and ${xs.at(-1)}`);

const fence = (lang, title, text) => `\`\`\`${lang} title=${yaml(title)}\n${text.trimEnd()}\n\`\`\`\n`;

function main() {
	for (const dir of ['docs', 'adr', 'examples']) rmSync(join(CONTENT, dir), { recursive: true, force: true });
	rmSync(join(CONTENT, 'changelog.md'), { force: true });

	const docs = docPages();
	const hosts = examplePages();
	for (const d of docs) routes.set(d.src, d.route);
	for (const h of hosts) routes.set(`examples/hosts/${h}.kdl`, `/examples/${h}/`);
	routes.set('CHANGELOG.md', '/changelog/');

	for (const d of docs) {
		const split = splitTitle(read(d.src), d.out);
		// Guide headings carry their file number ("05: CLI and exit codes"); the sidebar orders them.
		const title = split.title.replace(/^\d\d: /, '');
		const body = split.body;
		write(
			d.out,
			frontmatter({ title, editUrl: `${GITHUB}/edit/main/${d.src}`, sidebar: { order: d.order } }) +
				rewriteLinks(body, d.src),
		);
	}

	hosts.forEach((host, order) => {
		const kdl = read(`examples/hosts/${host}.kdl`);
		const uses = hostModules(kdl);
		const files = exampleFiles(host);
		const lead = uses.length
			? `The \`${host}\` host uses ${list(uses.map((u) => `\`${u}\``))}.`
			: `The \`${host}\` host.`;
		const outputs =
			files.length > 1
				? `knixl writes ${files.length} files for it: the host module and ${files.length - 1} side-file${files.length > 2 ? 's' : ''} it imports.`
				: 'knixl writes one file for it.';
		write(
			`examples/${host}.md`,
			frontmatter({
				title: host,
				description: `The ${host} example: KDL input and the Nix knixl generates from it.`,
				editUrl: `${GITHUB}/edit/main/examples/hosts/${host}.kdl`,
				sidebar: { order },
			}) +
				`${lead} ${outputs} The Nix below is the golden test output, so it is exactly what knixl emits.\n\n` +
				`## Input\n\n${fence('kdl', `hosts/${host}.kdl`, kdl)}\n## Generated\n\n` +
				files.map((f) => fence('nix', f.name, f.text)).join('\n'),
		);
	});

	const changelog = splitTitle(read('CHANGELOG.md'), 'Changelog');
	write(
		'changelog.md',
		frontmatter({ title: 'Changelog', editUrl: `${GITHUB}/edit/main/CHANGELOG.md`, tableOfContents: false }) +
			rewriteLinks(changelog.body, 'CHANGELOG.md'),
	);

	const data = {
		version: VERSION,
		web: { kdl: read('examples/hosts/web.kdl'), nix: golden('examples/expected/web.nix') },
		openssh: read('crates/knixl-modules/stdlib/openssh/knixl-module.kdl'),
	};
	mkdirSync(join(SITE, 'src/generated'), { recursive: true });
	writeFileSync(join(SITE, 'src/generated/site-data.json'), JSON.stringify(data, null, 2));

	console.log(
		`synced ${docs.length} docs, ${hosts.length} examples and the changelog (knixl ${VERSION}) into ${relative(SITE, CONTENT)}`,
	);
}

main();
